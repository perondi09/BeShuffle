-- Schema inicial: equivalente ao que o Hibernate (ddl-auto=update) criava para a entidade DailyAlbum.
-- Bancos que já existiam são marcados como baseline na versão 1 e não executam este script.
CREATE TABLE daily_albums (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spotify_album_id VARCHAR(255) NOT NULL,
    album_name       VARCHAR(255) NOT NULL,
    artist_name      VARCHAR(255) NOT NULL,
    image_url        TEXT,
    album_url        VARCHAR(255),
    release_date     VARCHAR(255),
    display_date     DATE         NOT NULL,
    full_album_json  TEXT,
    CONSTRAINT uk_daily_albums_spotify_album_id UNIQUE (spotify_album_id),
    CONSTRAINT uk_daily_albums_display_date UNIQUE (display_date)
);
