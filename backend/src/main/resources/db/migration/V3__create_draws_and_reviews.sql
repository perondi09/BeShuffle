-- Fase 4 parte 2: histórico de sorteios, fichas do dia (limite no servidor) e notas do Álbum do Dia.

-- Cada sorteio feito no site, por usuário logado ou por visitante (cookie bs_anon).
CREATE TABLE draws (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT REFERENCES users (id) ON DELETE CASCADE,
    anon_id          VARCHAR(36),
    spotify_album_id VARCHAR(64)              NOT NULL,
    album_name       VARCHAR(255)             NOT NULL,
    artist_name      VARCHAR(255),
    image_url        TEXT,
    draw_date        DATE                     NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_draws_owner CHECK (user_id IS NOT NULL OR anon_id IS NOT NULL)
);
CREATE INDEX ix_draws_draw_date ON draws (draw_date);
CREATE INDEX ix_draws_user_id ON draws (user_id);

-- Fichas gastas por dono ("u:<id>" ou "a:<uuid>") e dia. Uma linha por dono e dia; o gasto é um
-- UPDATE condicional (used < limite), então dois cliques ao mesmo tempo não gastam duas fichas.
CREATE TABLE draw_quota (
    owner_key  VARCHAR(64) NOT NULL,
    quota_date DATE        NOT NULL,
    used       INT         NOT NULL,
    CONSTRAINT pk_draw_quota PRIMARY KEY (owner_key, quota_date)
);

-- Nota (1 a 5) e comentário de uma conta para um Álbum do Dia; uma por conta e álbum.
CREATE TABLE reviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    daily_album_id BIGINT                   NOT NULL REFERENCES daily_albums (id) ON DELETE CASCADE,
    rating         INT                      NOT NULL,
    comment        VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT uk_reviews_user_album UNIQUE (user_id, daily_album_id)
);
CREATE INDEX ix_reviews_daily_album_id ON reviews (daily_album_id);
