-- Papel da conta (USER ou ADMIN) e banimento. O primeiro admin vem de ADMIN_EMAILS (nunca do código).
ALTER TABLE users ADD COLUMN role VARCHAR(10) DEFAULT 'USER' NOT NULL;
ALTER TABLE users ADD COLUMN banned_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN banned_reason VARCHAR(300);
ALTER TABLE users ADD CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'));
CREATE INDEX ix_users_created_at ON users (created_at);

-- Toda ação de admin (banir, desbanir, remover comentário, regerar álbum) fica registrada.
CREATE TABLE admin_actions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    action         VARCHAR(40)              NOT NULL,
    target_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    detail         VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_admin_actions_created_at ON admin_actions (created_at);

-- Um registro por visitante, dia e área. visitor_key: "u:<id>" (conta), "a:<hash do cookie bs_anon>" ou
-- "i:<hash do IP>" (visitante sem cookie). Nunca guarda o IP puro nem o valor do cookie.
CREATE TABLE daily_visits (
    visit_date  DATE        NOT NULL,
    visitor_key VARCHAR(64) NOT NULL,
    area        VARCHAR(10) NOT NULL,
    logged_in   BOOLEAN     NOT NULL,
    mobile      BOOLEAN     NOT NULL,
    CONSTRAINT pk_daily_visits PRIMARY KEY (visit_date, visitor_key, area),
    CONSTRAINT ck_daily_visits_area CHECK (area IN ('musica', 'filmes'))
);
